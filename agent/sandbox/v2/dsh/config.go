var cordisConfigTmpl = template.Must(template.New("cordis").Parse(cordisTemplate))

// RenderCordisConfig generates cordis.yml content from connector settings.
func RenderCordisConfig(cfg *ConnectorConfig) ([]byte, error) {
	var buf bytes.Buffer
	if err := cordisConfigTmpl.Execute(&buf, cfg); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
