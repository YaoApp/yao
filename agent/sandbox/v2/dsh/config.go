// ConnectorConfig holds LLM connector settings for cordis.yml rendering.
type ConnectorConfig struct {
	PiAiRoutes []PiAiRoute // dsh-llm-pi-ai provider routes
	IsWindows  bool
	Vision     bool
}

// PiAiRoute configures one dsh-llm-pi-ai provider route in cordis.yml.
type PiAiRoute struct {
	Name            string            // provider route key (e.g. "yao-primary", "yao-heavy")
	API             string            // wire protocol ("openai-completions" or "anthropic-messages")
	BaseURL         string            // endpoint URL
	APIKeyEnv       string            // env var name for the API key
	Models          []PiAiModelConfig // model catalog for this route
	Reasoning       string            // pi-ai reasoning level; empty = omit
	BudgetTokens    int               // > 0 → output thinkingBudgets
	NoDeveloperRole bool              // true → supportsDeveloperRole: false (safe for all non-OpenAI providers)
	ThinkingFormat  string            // connector-declared thinking wire format (e.g. "deepseek"); empty = let pi-ai detect from URL
}

// PiAiModelConfig declares a model's identity and capabilities for pi-ai.
type PiAiModelConfig struct {
	ID        string   // model identifier
	Input     []string // e.g. ["text"] or ["text", "image"]
	Reasoning bool     // true → render reasoningEfforts block
}

